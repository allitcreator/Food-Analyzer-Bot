/** Эмодзи для карточки блюда по ключевым словам в названии; порядок важен. */
const RULES: [string[], string][] = [
  [["кофе", "латте", "капучино"], "☕"],
  [["кур", "грудк"], "🍗"],
  [["овсян", "каш"], "🥣"],
  [["батончик", "шоколад"], "🍫"],
  [["салат"], "🥗"],
  [["суп", "борщ"], "🍲"],
  [["рыб", "лосос", "тунец"], "🐟"],
  [["йогурт", "творог", "молок"], "🥛"],
  [["яблок", "банан", "фрукт", "ягод"], "🍎"],
  [["хлеб", "бутерброд"], "🥪"],
];

export function foodEmoji(title: string): string {
  const t = title.toLowerCase().replace(/ё/g, "е");
  for (const [words, emoji] of RULES) {
    if (words.some((w) => t.includes(w))) return emoji;
  }
  return "🍽️";
}
