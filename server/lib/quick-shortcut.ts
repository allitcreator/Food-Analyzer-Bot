/**
 * Готовый шорткат iOS для быстрой записи и текст карточки `/quick`.
 *
 * Файл собирается `scripts/build-shortcuts.py`, подписывается на macOS
 * (`shortcuts sign -m anyone`) и лежит в репозитории — бот его только отдаёт.
 * Собрать на сервере нельзя: подпись умеет ставить только macOS, а без подписи
 * iOS отказывается импортировать файл.
 *
 * Токен в файл не зашивается: подпись покрывает содержимое, любая правка её
 * ломает. Поэтому токен пользователь вставляет руками после импорта — этому и
 * посвящена половина инструкции.
 */
import { join } from "node:path";

/** Имя файла = имя шортката на телефоне, поэтому оно человеческое. */
export const SHORTCUT_FILENAME = "Еда.shortcut";

export function shortcutPath(): string {
  // Рантайм стартует из корня проекта (в контейнере — /app), туда же Dockerfile
  // кладёт каталог shortcuts.
  return join(process.cwd(), "shortcuts", SHORTCUT_FILENAME);
}

/** Диагностика фото-ветки — отдаётся отдельной командой, не в /quick. */
export const DIAG_FILENAME = "Еда (диагностика).shortcut";

export function diagShortcutPath(): string {
  return join(process.cwd(), "shortcuts", DIAG_FILENAME);
}

