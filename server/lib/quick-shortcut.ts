/**
 * Готовый шорткат iOS для быстрой записи и текст карточки `/quick`.
 *
 * Файл собирается `scripts/build-shortcuts.py`, подписывается на macOS
 * (`shortcuts sign -m anyone`) и лежит в репозитории — бот его только отдаёт.
 * Собрать на сервере нельзя: подпись умеет ставить только macOS, а без подписи
 * iOS отказывается импортировать файл.
 *
 * Токен в файл не зашивается: подпись покрывает содержимое, любая правка её
 * ломает. Поэтому токен пользователь вставляет руками после импорта — этому и
 * посвящена половина инструкции.
 */
import { join } from "node:path";

/** Имя файла = имя шортката на телефоне, поэтому оно человеческое. */
export const SHORTCUT_FILENAME = "Еда.shortcut";

export function shortcutPath(): string {
  // Рантайм стартует из корня проекта (в контейнере — /app), туда же Dockerfile
  // кладёт каталог shortcuts.
  return join(process.cwd(), "shortcuts", SHORTCUT_FILENAME);
}

/** Диагностика фото-ветки — отдаётся отдельной командой, не в /quick. */
export const DIAG_FILENAME = "Еда (диагностика).shortcut";

export function diagShortcutPath(): string {
  return join(process.cwd(), "shortcuts", DIAG_FILENAME);
}

export function buildDiagText(): string {
  return [
    "🔬 *Диагностика фото-ветки*",
    "",
    "Шорткат кодирует один и тот же снимок двумя способами и показывает две " +
      "длины. Никуда ничего не отправляет, токен ему не нужен.",
    "",
    "*Что делать*",
    "1. Открой файл из следующего сообщения — он поставится как обычный шорткат.",
    "2. Запусти его и сними любой кадр, хоть стол.",
    "3. Пришли мне два числа с экрана.",
    "",
    "*Как они выглядят*",
    "`impl=123456 expl=123456`",
    "",
    "Числа должны совпасть — снимок-то один. Если `expl=0`, а `impl` больше " +
      "нуля, значит я неверно связал действия между собой, и чинить нужно это. " +
      "Если оба нуля — теряется сам снимок, и дело в съёмке.",
  ].join("\n");
}

export function buildShortcutCaption(): string {
  // Что делать с файлом, уже сказано в карточке — здесь только подпись.
  return "⚡ Шорткат «Еда»";
}

/**
 * Токен отдельным сообщением — чтобы копировался одним тапом.
 *
 * В общей карточке он тонет среди текста: тап по строке кода выделяет её
 * целиком, только если рядом нет другого содержимого.
 */
export function buildTokenMessage(token: string): string {
  return `\`${token}\``;
}

/**
 * Карточка /quick — только два шага, без которых шорткат не поставить.
 *
 * Всё остальное сюда не тащим: контракт эндпоинта лежит в QUICK-ENTRY.md, а
 * подсказки про «Ненадёжные команды» и правку токена нужны в редком случае и
 * стоили половины длины. Инструкцию, которую не читают, не прочитают и в
 * третий раз.
 */
export function buildQuickCardText(): string {
  return [
    "⚡ *Быстрая запись с телефона*",
    "",
    "Шорткат шлёт еду в этот чат — голосом, текстом или фото.",
    "",
    "1. Скопируй токен из следующего сообщения — тап по строке.",
    "2. Открой файл шортката и вставь токен, когда телефон спросит.",
    "",
    "⚠️ Токен разрешает запись в твой дневник. Утёк — жми «Сбросить».",
  ].join("\n");
}
