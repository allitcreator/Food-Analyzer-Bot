/**
 * Готовый шорткат iOS для быстрой записи и текст карточки `/quick`.
 *
 * Файл собирается `scripts/build-shortcuts.py`, подписывается на macOS
 * (`shortcuts sign -m anyone`) и лежит в репозитории — бот его только отдаёт.
 * Собрать на сервере нельзя: подпись умеет ставить только macOS, а без подписи
 * iOS отказывается импортировать файл.
 *
 * Токен в файл не зашивается: подпись покрывает содержимое, любая правка её
 * ломает. Поэтому токен пользователь вставляет руками после импорта — этому и
 * посвящена половина инструкции.
 */
import { join } from "node:path";

/** Имя файла = имя шортката на телефоне, поэтому оно человеческое. */
export const SHORTCUT_FILENAME = "Еда.shortcut";

export function shortcutPath(): string {
  // Рантайм стартует из корня проекта (в контейнере — /app), туда же Dockerfile
  // кладёт каталог shortcuts.
  return join(process.cwd(), "shortcuts", SHORTCUT_FILENAME);
}

export function buildShortcutCaption(): string {
  return "⚡ Шорткат «Еда» — сохрани файл и открой его, дальше по инструкции выше.";
}

/** Карточка /quick: как поставить шорткат, плюс контракт эндпоинта. */
export function buildQuickCardText(token: string, webhookUrl?: string | null): string {
  const base = webhookUrl?.replace(/\/+$/, "") || "https://<домен-бота>";
  return [
    "⚡ *Быстрая запись с телефона*",
    "",
    "Шорткат на iPhone шлёт еду сюда — карточка подтверждения приходит в этот чат.",
    "Голосом, текстом или фото.",
    "",
    "*Как поставить*",
    "1. Скачай файл из следующего сообщения и открой его — откроются «Команды».",
    "2. Если файл не открывается: Настройки → Команды → включи «Ненадёжные команды». " +
      "Тумблер появляется только после первого запуска любого шортката.",
    "3. Пролистай шорткат до действия «Получить содержимое URL», найди заголовок " +
      "`Authorization` и замени текст после `Bearer` на свой токен:",
    `\`${token}\``,
    "4. Готово. Запускай с домашнего экрана или из меню «Поделиться».",
    "",
    "*Если нужно собрать запрос самому*",
    `URL: \`${base}/api/quick\``,
    `Заголовок: \`Authorization: Bearer ${token}\``,
    'Тело: `{"text": "овсянка на молоке 250 г"}` или `{"imageBase64": "<JPEG в base64>"}`',
    "",
    "Можно и то и другое сразу: фото с подписью «это борщ, 400 г».",
    "",
    "⚠️ Токен разрешает запись в твой дневник. Утёк — жми «Сбросить», старый сразу перестанет работать.",
  ].join("\n");
}
